// ----- Calculator state -----
// An operation is: firstNumber operator secondNumber (e.g. 3 + 5)
let firstNumber = null;
let operator = null;
let secondNumber = null;

// ----- Basic math -----
function add(a, b) {
  return a + b;
}

function subtract(a, b) {
  return a - b;
}

function multiply(a, b) {
  return a * b;
}

function divide(a, b) {
  return a / b;
}

// Call the right math function for the operator
function operate(operator, a, b) {
  switch (operator) {
    case "+":
      return add(a, b);
    case "-":
      return subtract(a, b);
    case "*":
      return multiply(a, b);
    case "/":
      return divide(a, b);
    default:
      return null;
  }
}
